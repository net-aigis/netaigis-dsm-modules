#!/usr/bin/env bash
# Builds the kernel modules of one target from Synology's original GPL
# sources and toolchain. Used unchanged locally and in GitHub Actions.
#
# Usage: scripts/build.sh targets/<target>.conf
#
# Environment:
#   CACHE_DIR  downloaded archives  (default: ~/.cache/netaigis-dsm-modules)
#   BUILD_DIR  extracted sources    (default: /tmp/netaigis-dsm-build)
#   DIST_DIR   build results        (default: <repo>/dist)
#
# BUILD_DIR is a fixed path on purpose: kernel modules embed the build path,
# so identical paths are needed to compare local and CI results.
#
# KERNEL_DIR, TOOLCHAIN_PREFIX, LOCALVERSION, MODULE_DIR and REQUIRED_CONFIG
# may be omitted in the target (as in targets generated by
# scripts/target-gen.sh); they are then derived from the sources and
# modules.conf.
set -euo pipefail

REPO_DIR="$(cd "$(dirname "$0")/.." && pwd)"
TARGET_FILE="${1:?Usage: scripts/build.sh targets/<target>.conf}"

# shellcheck source=scripts/lib.sh
source "$REPO_DIR/scripts/lib.sh"

BUILD_DIR="${BUILD_DIR:-/tmp/netaigis-dsm-build}"
DIST_DIR="${DIST_DIR:-$REPO_DIR/dist}"

[[ -f "$TARGET_FILE" ]] || die "Target not found: $TARGET_FILE"

TARGET="$(basename "$TARGET_FILE" .conf)"

# /usr/sbin is often not in PATH for regular users.
MODINFO="$(command -v modinfo || echo /usr/sbin/modinfo)"
[[ -x "$MODINFO" ]] || die "modinfo not found (package kmod)"

# shellcheck source=/dev/null
source "$TARGET_FILE"

# Prints field $2 (2 = directory, 3 = option) of module $1 in modules.conf.
module_field() {
  local value
  value="$(awk -v m="$1" -v f="$2" '!/^#/ && $1 == m { print $f }' "$REPO_DIR/modules.conf")"
  [[ -n "$value" ]] || die "Module $1 is not listed in modules.conf"
  echo "$value"
}

if [[ -z "${MODULE_DIR:-}" ]]
then
  MODULE_DIR="$(for module in $MODULES; do module_field "$module" 2; done | sort -u | xargs)"
fi

if [[ -z "${REQUIRED_CONFIG:-}" ]]
then
  REQUIRED_CONFIG="$(for module in $MODULES; do echo "$(module_field "$module" 3)=m"; done | xargs)"
fi

kernel_archive="$(fetch "$KERNEL_URL" "$KERNEL_SHA256")"
toolchain_archive="$(fetch "$TOOLCHAIN_URL" "$TOOLCHAIN_SHA256")"

target_build="$BUILD_DIR/$TARGET"

log "Extract sources to $target_build"

# The toolchain archive contains read-only directories.
if [[ -d "$target_build" ]]
then
  chmod -R u+w "$target_build"
  rm -rf "$target_build"
fi

mkdir -p "$target_build"
tar -xJf "$kernel_archive" -C "$target_build"

if [[ -z "${KERNEL_DIR:-}" ]]
then
  mapfile -t top_dirs < <(find "$target_build" -mindepth 1 -maxdepth 1 -type d -printf '%f\n')
  (( ${#top_dirs[@]} == 1 )) || die "Kernel archive must contain exactly one directory"
  KERNEL_DIR="${top_dirs[0]}"
fi

kernel_src="$target_build/$KERNEL_DIR"
[[ -f "$kernel_src/Makefile" ]] || die "Kernel source missing: $kernel_src"

tar -xJf "$toolchain_archive" -C "$target_build"

if [[ -n "${TOOLCHAIN_PREFIX:-}" ]]
then
  cross_compile="$target_build/$TOOLCHAIN_PREFIX"
else
  compiler="$(find "$target_build" -mindepth 3 -maxdepth 3 -path '*/bin/*-linux-*-gcc' \
    -not -path "$kernel_src/*" | sort | head -n 1)"
  [[ -n "$compiler" ]] || die "No cross compiler found in the toolchain"
  cross_compile="${compiler%gcc}"
fi

[[ -x "${cross_compile}gcc" ]] || die "Toolchain compiler missing: ${cross_compile}gcc"

make_args=(
  -C "$kernel_src"
  ARCH="$ARCH"
  CROSS_COMPILE="$cross_compile"
)

log "Configure kernel ($SYNOCONFIG)"
[[ -f "$kernel_src/$SYNOCONFIG" ]] || die "Kernel config missing: $SYNOCONFIG"
cp "$kernel_src/$SYNOCONFIG" "$kernel_src/.config"
make "${make_args[@]}" olddefconfig

# The suffix the kernel release has beyond the version and configuration,
# e.g. "+" for 4.4.302+.
if [[ -z "${LOCALVERSION+set}" ]]
then
  base_release="$(make -s "${make_args[@]}" LOCALVERSION= kernelrelease)"
  [[ "$KERNEL_RELEASE" == "$base_release"* ]] ||
    die "Kernel release is $base_release, expected $KERNEL_RELEASE"
  LOCALVERSION="${KERNEL_RELEASE#"$base_release"}"
fi

make_args+=(LOCALVERSION="$LOCALVERSION")

for option in $REQUIRED_CONFIG
do
  grep -qx "$option" "$kernel_src/.config" ||
    die "Kernel option not set as required: $option"
done

release="$(make -s "${make_args[@]}" kernelrelease)"
[[ "$release" == "$KERNEL_RELEASE" ]] ||
  die "Kernel release is $release, expected $KERNEL_RELEASE"

make -j"$(nproc)" "${make_args[@]}" modules_prepare

for dir in $MODULE_DIR
do
  log "Build modules in $dir"
  make -j"$(nproc)" "${make_args[@]}" M="$dir" modules
done

out="$DIST_DIR/$TARGET"
rm -rf "$out"
mkdir -p "$out"

log "Verify and collect modules"
for module in $MODULES
do
  ko=""
  for dir in $MODULE_DIR
  do
    [[ -f "$kernel_src/$dir/$module.ko" ]] && ko="$kernel_src/$dir/$module.ko"
  done
  [[ -n "$ko" ]] || die "Module not built: $module.ko"

  vermagic="$("$MODINFO" -F vermagic "$ko")"
  [[ "$vermagic" == "$KERNEL_RELEASE "* ]] ||
    die "$module.ko has vermagic '$vermagic', expected $KERNEL_RELEASE"

  cp "$ko" "$out/"
done

(
  cd "$out"
  sha256sum ./*.ko | sed 's| \./| |' > SHA256SUMS
)

{
  echo "target=$TARGET"
  echo "dsm_version=$DSM_VERSION"
  echo "platform=$PLATFORM"
  echo "kernel_release=$KERNEL_RELEASE"
  echo "kernel_sha256=$KERNEL_SHA256"
  echo "toolchain_sha256=$TOOLCHAIN_SHA256"
  echo "repo_commit=$(git -C "$REPO_DIR" rev-parse --verify -q HEAD 2>/dev/null || echo unknown)"
  echo "build_dir=$BUILD_DIR"
  for module in $MODULES
  do
    echo "vermagic_$module=$("$MODINFO" -F vermagic "$out/$module.ko")"
  done
} > "$out/build-info.txt"

log "Done: $out"
cat "$out/SHA256SUMS"
