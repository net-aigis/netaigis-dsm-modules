#!/usr/bin/env bash
# Derives the build target of a device fingerprint from Synology's archive:
# the GPL kernel source and the toolchain of its DSM build and platform.
# Both archives are downloaded into CACHE_DIR to pin their SHA-256.
#
# Usage: scripts/target-gen.sh fingerprints/<id>.txt <output directory>
#
# Writes <output directory>/dsm-<version>-<build>_<platform>.conf and prints
# its path.
set -euo pipefail

REPO_DIR="$(cd "$(dirname "$0")/.." && pwd)"
FP_FILE="${1:?Usage: scripts/target-gen.sh <fingerprint> <output directory>}"
OUT_DIR="${2:?Usage: scripts/target-gen.sh <fingerprint> <output directory>}"
ARCHIVE_URL="${SYNOLOGY_ARCHIVE_URL:-https://archive.synology.com/download/ToolChain}"

# shellcheck source=scripts/lib.sh
source "$REPO_DIR/scripts/lib.sh"

id="$("$REPO_DIR/scripts/fingerprint.sh" "$FP_FILE")"

fp() {
  sed -n "s/^$1=//p" "$FP_FILE"
}

platform="$(fp platform)"
build="$(fp dsm_build)"
machine="$(fp arch)"

case "$machine" in
  x86_64)  arch=x86_64 toolchain_arch=x86_64 ;;
  aarch64) arch=arm64  toolchain_arch=armv8 ;;
  *)       die "Unsupported architecture: $machine" ;;
esac

# Absolute download links of an archive index page.
links() {
  curl -fsSL --retry 3 "$ARCHIVE_URL/$1" |
    grep -o 'href="https://global\.synologydownload\.com/[^"]*"' |
    sed 's/^href="//; s/"$//'
}

# The release directory (e.g. 7.3-86009) of the DSM build in an index.
release_dir() {
  curl -fsSL --retry 3 "$ARCHIVE_URL/$1" |
    grep -o "href=\"/download/ToolChain/$1/[0-9.]*-$build\"" |
    sed 's|.*/||; s/"$//' | sort -u
}

# Exactly one link must match, anything else means the archive changed.
only_one() {
  local what="$1"
  local matches
  matches="$(cat)"
  [[ -n "$matches" ]] || die "No $what in Synology's archive for fingerprint $id"
  [[ "$(wc -l <<< "$matches")" -eq 1 ]] ||
    die "Several ${what}s for fingerprint $id: $(echo "$matches" | xargs)"
  echo "$matches"
}

gpl_index="Synology%20NAS%20GPL%20Source"
dsm_release="$(release_dir "$gpl_index" | only_one "GPL source release for build $build")"

kernel_url="$(links "$gpl_index/$dsm_release" |
  grep -E "/$dsm_release/$platform/linux-[0-9][0-9.x]*\.txz$" |
  only_one "kernel source for $platform")"

toolchain_release="$(release_dir toolchain | only_one "toolchain release for build $build")"

toolchain_url="$(links "toolchain/$toolchain_release" |
  grep -E "/$platform-gcc[0-9]+_glibc[0-9]+_$toolchain_arch-GPL\.txz$" |
  only_one "toolchain for $platform ($toolchain_arch)")"

kernel_sha256="$(sha256sum "$(fetch "$kernel_url")" | cut -d' ' -f1)"
toolchain_sha256="$(sha256sum "$(fetch "$toolchain_url")" | cut -d' ' -f1)"

mkdir -p "$OUT_DIR"
target_file="$OUT_DIR/dsm-${dsm_release}_$platform.conf"

cat > "$target_file" <<EOF
# Generated by scripts/target-gen.sh for fingerprint $id

DSM_VERSION="$dsm_release"
PLATFORM="$platform"
MACHINE="$machine"
KERNEL_RELEASE="$(fp kernel_release)"

KERNEL_URL="$kernel_url"
KERNEL_SHA256="$kernel_sha256"

TOOLCHAIN_URL="$toolchain_url"
TOOLCHAIN_SHA256="$toolchain_sha256"

ARCH="$arch"
SYNOCONFIG="synoconfigs/$platform"

MODULES="$(fp modules)"
EOF

echo "$target_file"
